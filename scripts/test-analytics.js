const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '../js/analytics.js'), 'utf8');
function setup({ host = 'zangli.org', stored = '', blocked = false, offline = false, redirecting = false } = {}) {
	const listeners = {}, scripts = [], store = { value: stored };
	const buttons = ['granted', 'denied'].map(choice => ({ dataset: { analyticsChoice: choice }, setAttribute() {}, addEventListener(type, fn) { this.click = fn; } }));
	const panel = { querySelectorAll: () => buttons };
	const status = { dataset: { granted: 'yes', denied: 'no' } };
	const context = vm.createContext({ URL, Date, Set, location: { protocol: 'https:', hostname: host, pathname: '/tw/date/2027-02-06', origin: `https://${host}` }, navigator: { onLine: !offline }, matchMedia: () => ({ matches: false }), localStorage: { getItem() { if (blocked) throw Error('blocked'); return store.value; }, setItem(k, v) { if (blocked) throw Error('blocked'); store.value = v; } }, document: { readyState: 'complete', referrer: 'https://example.org/private?q=secret', cookie: '', getElementById: id => id === 'analyticsConsent' ? panel : status, createElement: () => ({ remove() {} }), head: { appendChild: s => scripts.push(s) }, addEventListener() {} }, addEventListener: (type, fn) => { listeners[type] = fn; } });
	context.window = context;
	context.zangliRedirecting = redirecting;
	vm.runInContext(source, context);
	const events = () => Array.from(context.dataLayer || []).filter(x => x[0] === 'event');
	return { context, scripts, buttons, listeners, events, store };
}
const a = setup();
assert.equal(a.scripts.length, 0);
a.context.zangliTrack('calendar_export');
assert.equal(a.context.dataLayer, undefined, 'No pre-consent event queue');
a.buttons[1].click(); assert.equal(a.scripts.length, 0);
a.buttons[0].click(); assert.equal(a.scripts.length, 1);
a.scripts[0].onload();
a.buttons[0].click(); assert.equal(a.events().length, 1, 'Repeated allow does not duplicate page view');
a.context.zangliTrack('calendar_export', { kind: 'annual', date: '2027-02-06', text: 'secret' });
assert.equal(a.events().length, 2);
const payload = a.events()[1][2];
assert.equal(payload.page_location, 'https://zangli.org/tw/');
assert.equal(payload.page_referrer, 'https://example.org/');
assert.equal(payload.date, undefined); assert.equal(payload.text, undefined);
a.context.zangliTrack('arbitrary'); assert.equal(a.events().length, 2);
a.buttons[1].click();
a.context.zangliTrack('calendar_export'); assert.equal(a.events().length, 2);
assert.equal(a.context['ga-disable-G-WY2HDCMYRL'], true);
const pending = setup(); pending.buttons[0].click(); pending.buttons[1].click(); pending.scripts[0].onload(); assert.equal(pending.events().length, 0);
assert.equal(setup({ stored: 'granted', redirecting: true }).scripts.length, 0, 'Language redirect must not count the abandoned page');
const local = setup({ host: 'localhost', stored: 'granted' }); assert.equal(local.scripts.length, 0);
const preview = setup({ host: 'preview.pages.dev', stored: 'granted' }); assert.equal(preview.scripts.length, 0);
const blocked = setup({ blocked: true }); blocked.buttons[0].click(); assert.equal(blocked.scripts.length, 1);
const offline = setup({ stored: 'granted', offline: true }); assert.equal(offline.scripts.length, 0); offline.context.navigator.onLine = true; offline.listeners.online(); assert.equal(offline.scripts.length, 1);
const cross = setup({ stored: 'granted' }); cross.scripts[0].onload(); cross.listeners.storage({ key: 'zangli-analytics-consent', newValue: 'denied' }); cross.context.zangliTrack('calendar_export'); assert.equal(cross.events().length, 1);
const lateOffline = setup({ stored: 'granted' }); lateOffline.context.navigator.onLine = false; lateOffline.scripts[0].onload(); assert.equal(lateOffline.events().length, 0); lateOffline.context.navigator.onLine = true; lateOffline.listeners.online(); assert.equal(lateOffline.events().length, 1);
const failure = setup({ stored: 'granted' }); failure.scripts[0].onerror(); assert.equal(failure.context.dataLayer.length, 0);
console.log('Analytics checks passed: consent, revocation, allowlist, sanitized metadata, production-only, storage failure and offline recovery.');
